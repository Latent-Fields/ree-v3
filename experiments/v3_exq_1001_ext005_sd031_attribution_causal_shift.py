def main() -> Tuple[Dict[str, Any], Path, bool]:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true",
                        help="tiny smoke run (2 seeds, 4 episodes/blocks)")
    args = parser.parse_args()

    torch.manual_seed(0)
    np.random.seed(0)
    random.seed(0)

    manifest = run_experiment(dry_run=args.dry_run)
    out_path = write_flat_manifest(manifest, dry_run=args.dry_run,
                                   script_path=Path(__file__), stamp=False)

    print("Outcome: %s" % manifest["outcome"], flush=True)
    print("label:   %s" % manifest["interpretation"]["label"], flush=True)
    for c in manifest["criteria"]:
        # red-team finding-8 follow-up (second pass, 2026-09-04): print ALL THREE
        # triple-gate sub-quantities, not just gap-vs-bare -- printing only "mean"
        # (gap-vs-bare) risked reading mean>=requirement with passed=False as
        # confusing/inconsistent when the chance or shuffled-action sub-gate is what
        # actually failed.
        print("  %-42s load_bearing=%-5s passed=%-5s bare_gap=%s chance_gap=%s shuffled_gap=%s"
              % (c["name"], c["load_bearing"], c["passed"],
                 ("%.4f" % c["gap_vs_bare"]["mean"]) if c["gap_vs_bare"]["mean"] == c["gap_vs_bare"]["mean"] else "nan",
                 ("%.4f" % c["gap_vs_chance"]["mean"]) if c["gap_vs_chance"]["mean"] == c["gap_vs_chance"]["mean"] else "nan",
                 ("%.4f" % c["gap_vs_shuffled_action"]["mean"]) if c["gap_vs_shuffled_action"]["mean"] == c["gap_vs_shuffled_action"]["mean"] else "nan"),
              flush=True)
    for p in manifest["interpretation"]["preconditions"]:
        print("  precondition %-34s met=%-5s measured=%s"
              % (p["name"], p.get("met"), p.get("measured")), flush=True)
    print("Result pack written to: %s" % out_path, flush=True)
    return manifest, out_path, bool(args.dry_run)


