def _action_pathway_probe(model: E2WorldForward, z_prev: torch.Tensor,
                          action_dim: int) -> float:
    n = min(256, z_prev.shape[0])
    a_i = torch.zeros(n, action_dim)
    a_i[:, 0] = 1.0
    a_j = torch.zeros(n, action_dim)
    a_j[:, min(2, action_dim - 1)] = 1.0
    with torch.no_grad():
        return float((model(z_prev[:n], a_i) - model(z_prev[:n], a_j)).norm(dim=-1).mean())


def _train_head(z_prev: torch.Tensor, action: torch.Tensor, z_obs: torch.Tensor,
                 n_train: int, action_dim: int, seed: int, epochs: int, lr: float,
                 start_from: Optional[E2WorldForward] = None) -> Tuple[E2WorldForward, List[Dict[str, Any]], float]:
    """Train (or continue-train, if `start_from` is given) an E2WorldForward head on
    (z_prev[:n_train], action[:n_train]) -> z_obs[:n_train]. Wiring measured AT the
    entry weights (i.e. at true init for a fresh model, or at the carried-over weights
    for a readaptation pass) so it reflects a property of the module at that point, not
    what THIS phase's training subsequently taught it."""
    if start_from is None:
        model = E2WorldForward(E2WorldConfig(
            use_e2_world_forward=True, z_world_dim=WORLD_DIM, action_dim=action_dim,
        ))
    else:
        model = copy.deepcopy(start_from)
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    gen = torch.Generator().manual_seed(int(seed))
    curve: List[Dict[str, Any]] = []
    wiring_at_entry = _action_pathway_probe(model, z_prev, action_dim)

    for epoch in range(epochs):
        perm = torch.randperm(n_train, generator=gen)
        last_loss = float("nan")
        for i in range(0, n_train, HEAD_BATCH):
            idx = perm[i:i + HEAD_BATCH]
            loss = model.compute_loss(model(z_prev[idx], action[idx]), z_obs[idx].detach())
            opt.zero_grad()
            loss.backward()
            opt.step()
            last_loss = float(loss.detach())
        if (epoch + 1) % AUROC_CURVE_EVERY == 0 or epoch == epochs - 1:
            curve.append({"epoch": epoch + 1, "train_loss": last_loss})
    return model, curve, wiring_at_entry


def _move_ok_auroc_block(model: E2WorldForward, z_prev: torch.Tensor, action: torch.Tensor,
                          z_obs: torch.Tensor, cls: np.ndarray, drift: np.ndarray,
                          seed_for_shuffle: int) -> Dict[str, Any]:
    """Per_stratum AUROC block (comparator / bare / shuffled-action) over a fixed
    (z_prev, action, z_obs, cls, drift) evaluation set -- caller controls which rows
    are passed (a held-out slice)."""
    n = z_prev.shape[0]
    gen = torch.Generator().manual_seed(int(seed_for_shuffle) + 77)
    with torch.no_grad():
        res = model.comparator_residual(z_obs, z_prev, action).norm(dim=-1).numpy()
        perm = torch.randperm(n, generator=gen)
        res_shuf = model.comparator_residual(z_obs, z_prev, action[perm]).norm(dim=-1).numpy()
        fwd_mse = float(torch.nn.functional.mse_loss(model(z_prev, action), z_obs))
    bare = (z_obs - z_prev).norm(dim=-1).numpy()

    per_stratum: Dict[str, Any] = {}
    for c in ("STAY", "MOVE_OK", "MOVE_BLOCKED"):
        sel = (cls == c)
        n1 = int(drift[sel].sum())
        n0 = int((~drift[sel]).sum())
        per_stratum[c] = {
            "n_drift": n1, "n_no_drift": n0,
            "auroc_comparator": _auroc(res[sel], drift[sel]),
            "auroc_bare_delta": _auroc(bare[sel], drift[sel]),
            "auroc_shuffled_action": _auroc(res_shuf[sel], drift[sel]),
            "verdict_bearing": c == "MOVE_OK",
        }
    mo = per_stratum["MOVE_OK"]
    return {
        "auroc_move_ok": mo["auroc_comparator"],
        "auroc_bare_move_ok": mo["auroc_bare_delta"],
        "auroc_shuffled_move_ok": mo["auroc_shuffled_action"],
        "heldout_forward_mse": fwd_mse,
        "per_stratum": per_stratum,
    }


def _run_seed(seed: int, dry_run: bool, zg: ZGoalStreamAccumulator,
              post_episodes: int) -> Dict[str, Any]:
    env_probe = _build_env(seed)
    action_dim = env_probe.action_dim
    agent = seeded_construct(seed, lambda: _build_agent(env_probe))

    episodes = 4 if dry_run else EPISODES_PER_PHASE
    p0a_steps = 30 if dry_run else P0A_STEPS_PER_EPISODE
    pre_blocks = 4 if dry_run else EPISODES_PER_PHASE
    per_block = 90 if dry_run else TRANSITIONS_PER_BLOCK
    post_blocks = 4 if dry_run else post_episodes

    p0a_stats, guard = _run_p0a(agent, seed, episodes, p0a_steps, dry_run)
    for p in agent.latent_stack.parameters():
        p.requires_grad_(False)

    # ---------------- PRE-shift: identical to 995's P1_COLLECT + BASE training ----------
    pre_env = _build_env(seed + 500)
    buf_pre = _collect_transitions(agent, pre_env, seed, pre_blocks, per_block, "P1_COLLECT")
    n_pre = buf_pre["n_transitions"]
    n_train_pre = int((1.0 - HELDOUT_FRACTION_PRE) * n_pre)

    arm_rows: List[Dict[str, Any]] = []

    with arm_cell(seed, config_slice=_config_slice(seed, "PRE_BASE"),
                  script_path=Path(__file__), config_slice_declared=True,
                  extra_ineligible_reasons=[
                      "shared_p0a_encoder_and_transition_buffer_across_arms",
                      "post_arms_initialized_from_pre_base_trained_weights"]) as cell:
        pre_model, pre_curve, pre_wiring_init = _train_head(
            buf_pre["z_prev"], buf_pre["action"], buf_pre["z_obs"],
            n_train_pre, action_dim, seed, HEAD_EPOCHS, HEAD_LR, start_from=None)
        held_pre = slice(n_train_pre, n_pre)
        pre_eval = _move_ok_auroc_block(
            pre_model, buf_pre["z_prev"][held_pre], buf_pre["action"][held_pre],
            buf_pre["z_obs"][held_pre], buf_pre["cls"][held_pre], buf_pre["drift"][held_pre],
            seed_for_shuffle=seed)
        row_pre: Dict[str, Any] = {
            "arm_id": "PRE_BASE", "seed": int(seed), "verdict_bearing": False,
            "heldout_loss_curve": pre_curve,
            "action_pathway_wiring_at_init": pre_wiring_init,
            "action_pathway_wiring_trained": _action_pathway_probe(
                pre_model, buf_pre["z_prev"], action_dim),
        }
        row_pre.update(pre_eval)
        cell.stamp(row_pre)
    arm_rows.append(row_pre)

    pre_class_fracs = _class_fractions(buf_pre)

    # ---------------- POST-shift: build a rewired env, collect fresh transitions --------
    post_env, shift_record = _build_shifted_env(seed + 700)
    buf_post = _collect_transitions(agent, post_env, seed, post_blocks, per_block, "P3_COLLECT")
    n_post = buf_post["n_transitions"]
    n_readapt_train = int(READAPT_TRAIN_FRACTION * n_post)
    readapt_slice = slice(0, n_readapt_train)
    heldout_slice = slice(n_readapt_train, n_post)

    post_class_fracs = _class_fractions(buf_post)
    surface_stat_deviation = max(
        abs(pre_class_fracs[k] - post_class_fracs[k])
        for k in ("STAY", "MOVE_OK", "MOVE_BLOCKED", "drift_fraction")
    )

    with arm_cell(seed, config_slice=_config_slice(seed, "POST_FROZEN"),
                  script_path=Path(__file__), config_slice_declared=True,
                  extra_ineligible_reasons=[
                      "shared_p0a_encoder_and_transition_buffer_across_arms",
                      "post_arms_initialized_from_pre_base_trained_weights"]) as cell:
        frozen_eval = _move_ok_auroc_block(
            pre_model, buf_post["z_prev"][heldout_slice], buf_post["action"][heldout_slice],
            buf_post["z_obs"][heldout_slice], buf_post["cls"][heldout_slice],
            buf_post["drift"][heldout_slice], seed_for_shuffle=seed + 1)
        row_frozen: Dict[str, Any] = {
            "arm_id": "POST_FROZEN", "seed": int(seed), "verdict_bearing": True,
            "n_readapt_train": int(n_readapt_train), "n_heldout": int(n_post - n_readapt_train),
        }
        row_frozen.update(frozen_eval)
        cell.stamp(row_frozen)
    arm_rows.append(row_frozen)

    with arm_cell(seed, config_slice=_config_slice(seed, "POST_READAPT"),
                  script_path=Path(__file__), config_slice_declared=True,
                  extra_ineligible_reasons=[
                      "shared_p0a_encoder_and_transition_buffer_across_arms",
                      "post_arms_initialized_from_pre_base_trained_weights"]) as cell:
        readapt_model, readapt_curve, readapt_wiring_entry = _train_head(
            buf_post["z_prev"][readapt_slice], buf_post["action"][readapt_slice],
            buf_post["z_obs"][readapt_slice], n_readapt_train, action_dim, seed + 2000,
            READAPT_EPOCHS, HEAD_LR, start_from=pre_model)
        readapt_eval = _move_ok_auroc_block(
            readapt_model, buf_post["z_prev"][heldout_slice], buf_post["action"][heldout_slice],
            buf_post["z_obs"][heldout_slice], buf_post["cls"][heldout_slice],
            buf_post["drift"][heldout_slice], seed_for_shuffle=seed + 1)
        row_readapt: Dict[str, Any] = {
            "arm_id": "POST_READAPT", "seed": int(seed), "verdict_bearing": True,
            "n_readapt_train": int(n_readapt_train), "n_heldout": int(n_post - n_readapt_train),
            "readapt_loss_curve": readapt_curve,
            "action_pathway_wiring_at_readapt_entry": readapt_wiring_entry,
        }
        row_readapt.update(readapt_eval)
        cell.stamp(row_readapt)
    arm_rows.append(row_readapt)

    zg.observe(agent)

    d1 = ((row_frozen["auroc_move_ok"] or 0.0) - (row_frozen["auroc_bare_move_ok"] or 0.0))
    d2 = ((row_readapt["auroc_move_ok"] or 0.0) - (row_readapt["auroc_bare_move_ok"] or 0.0))
    # red-team finding 8 (CLEAR-with-note, fixed): this per-seed print is a raw
    # single-seed gap-vs-bare-only signal (> 0.0), NOT the pre-registered triple-gated,
    # cross-seed-noise-aware adjudication computed in _adjudicate -- labelled explicitly
    # so console output during a run cannot be mistaken for the final verdict.
    print("gap_vs_bare (uncalibrated, single-seed, informational only): %s"
          % ("positive" if (d1 > 0.0 or d2 > 0.0) else "non-positive"), flush=True)

    return {
        "seed": int(seed),
        "p0a": p0a_stats,
        "zworld_encoder_guard": guard,
        "shift_record": shift_record,
        "n_transitions_pre": n_pre,
        "n_transitions_post": n_post,
        "n_env_drift_flag_disagreements_pre": buf_pre["n_flag_disagree"],
        "n_env_drift_flag_disagreements_post": buf_post["n_flag_disagree"],
        "class_fractions_pre": pre_class_fracs,
        "class_fractions_post": post_class_fracs,
        "surface_stat_max_deviation": surface_stat_deviation,
        "action_counts_pre": buf_pre["action_counts"],
        "action_counts_post": buf_post["action_counts"],
        "arms": arm_rows,
    }


