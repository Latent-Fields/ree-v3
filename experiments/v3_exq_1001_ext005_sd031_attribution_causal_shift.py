# --------------------------------------------------------------------- utilities
def _auroc(scores: np.ndarray, labels: np.ndarray) -> Optional[float]:
    """Rank-based AUROC. None when either class is empty."""
    s = np.asarray(scores, dtype=float)
    y = np.asarray(labels, dtype=bool)
    n1 = int(y.sum())
    n0 = int((~y).sum())
    if n1 == 0 or n0 == 0:
        return None
    order = s.argsort(kind="mergesort")
    ranks = np.empty(len(s), dtype=float)
    ranks[order] = np.arange(1, len(s) + 1, dtype=float)
    _, inv, counts = np.unique(s, return_inverse=True, return_counts=True)
    sums = np.zeros(len(counts), dtype=float)
    np.add.at(sums, inv, ranks)
    ranks = (sums / counts)[inv]
    return float((ranks[y].sum() - n1 * (n1 + 1) / 2.0) / (n1 * n0))


def _mean_sd(values: List[float]) -> Tuple[float, float]:
    arr = np.asarray([v for v in values if v is not None], dtype=float)
    if arr.size == 0:
        return float("nan"), float("nan")
    sd = float(arr.std(ddof=1)) if arr.size > 1 else 0.0
    return float(arr.mean()), sd


def _worst_low(values: List[Tuple[float, Any]]) -> Tuple[Optional[float], Any]:
    vals = [(v, k) for v, k in values if v is not None]
    if not vals:
        return None, None
    v, k = min(vals, key=lambda t: t[0])
    return float(v), k


def _worst_interval(values: List[Tuple[float, Any]], centre: float) -> Tuple[Optional[float], Any]:
    vals = [(v, k) for v, k in values if v is not None]
    if not vals:
        return None, None
    v, k = max(vals, key=lambda t: abs(t[0] - centre))
    return float(v), k


def _build_env(seed: int) -> CausalGridWorldV2:
    return CausalGridWorldV2(seed=seed, **ENV_KWARGS)


def _build_agent(env: CausalGridWorldV2) -> REEAgent:
    cfg = REEConfig.from_dims(
        body_obs_dim=env.body_obs_dim,
        world_obs_dim=env.world_obs_dim,
        action_dim=env.action_dim,
        world_dim=WORLD_DIM,
        alpha_world=ALPHA_WORLD,
    )
    return REEAgent(cfg)


def _encode_world(split_encoder, obs_dict) -> torch.Tensor:
    body = obs_dict["body_state"].float()
    world = obs_dict["world_state"].float()
    if body.dim() == 1:
        body = body.unsqueeze(0)
    if world.dim() == 1:
        world = world.unsqueeze(0)
    with torch.no_grad():
        return split_encoder(body, world)[1]


def _shift_action_map(env: CausalGridWorldV2) -> Dict[str, Any]:
    """Overwrite env._action_map with a single 4-cycle rotation of the 4 movement
    actions (offset WORLD_SHIFT_ROTATION_OFFSET), leaving action STAY_ACTION fixed at
    (0, 0). Deterministic, applied ONCE. Returns an audit record."""
    canonical = dict(env._action_map)
    move_keys = sorted(k for k in canonical if k != STAY_ACTION)
    n = len(move_keys)
    shifted = dict(canonical)
    for i, k in enumerate(move_keys):
        shifted[k] = canonical[move_keys[(i + WORLD_SHIFT_ROTATION_OFFSET) % n]]
    env._action_map = shifted
    n_rewired = sum(1 for k in move_keys if shifted[k] != canonical[k])
    assert shifted[STAY_ACTION] == (0, 0), "STAY_ACTION must never be rewired"
    return {
        "canonical_action_map": {str(k): list(v) for k, v in canonical.items()},
        "shifted_action_map": {str(k): list(v) for k, v in shifted.items()},
        "n_movement_actions": n,
        "n_actions_rewired": int(n_rewired),
        "rotation_offset": WORLD_SHIFT_ROTATION_OFFSET,
    }


def _build_shifted_env(seed: int) -> Tuple[CausalGridWorldV2, Dict[str, Any]]:
    env = _build_env(seed)
    record = _shift_action_map(env)
    return env, record


